import assert from 'node:assert/strict';
import { check } from '../src/check.mjs';
import { classify, transition } from '../src/engine.mjs';
import { Globalping } from '../src/globalping.mjs';
import { GitHub } from '../src/github.mjs';
import { repository } from '../src/config.mjs';
if (repository !== 'espectre00/slatedsk-status' || !process.env.GITHUB_TOKEN || !process.env.GLOBALPING_TOKEN) throw new Error('Entorno de ensayo incompleto');
const gp = new Globalping(process.env.GLOBALPING_TOKEN);
const gh = new GitHub(repository, process.env.GITHUB_TOKEN);
const marker = '<!-- slatedsk-monitor:validation -->';
const testIssues = async () => (await gh.listIssues()).filter(i => i.user.login === 'github-actions[bot]' && i.body?.includes(marker));
async function round(url, previous) {
  const component = {id:'validation',name:'Prueba técnica del monitor (sin impacto en SlateDsk)',kind:'html',url};
  const primary = await check(component), retry = await check(component);
  const regions = [];
  for (const region of ['EU','NA']) regions.push(await gp.check(component,region));
  const at = new Date().toISOString();
  console.log(JSON.stringify({at,primary,retry,regions}));
  return {...component,...transition(previous,{status:classify(primary,retry,regions),primary,retry,regions},at)};
}
const before = await testIssues();
const failed = await round('https://status.slatedsk.com/fixtures/missing-test-endpoint',{});
assert.equal(failed.status,'outage','El destino inexistente debe fallar desde las tres ubicaciones');
await gh.sync([failed],failed.checkedAt);
const opened = (await testIssues()).filter(i=>i.state==='open');
assert.equal(opened.length,1);
await gh.sync([failed],failed.checkedAt);
assert.equal((await testIssues()).length,before.length+(before.some(i=>i.state==='open')?0:1),'No debe duplicar la incidencia');
const first = await round('https://status.slatedsk.com/fixtures/healthy.html',failed);
assert.equal(first.goodRounds,1);assert.equal(first.activeIncident,true);
await gh.sync([first],first.checkedAt);
assert.equal((await testIssues()).find(i=>i.number===opened[0].number).state,'open');
const second = await round('https://status.slatedsk.com/fixtures/healthy.html',first);
assert.equal(second.goodRounds,2);
await gh.sync([second],second.checkedAt);
const final = (await testIssues()).find(i=>i.number===opened[0].number);
assert.equal(final.state,'closed');
assert.ok((await gh.all(`issues/${final.number}/comments`)).some(c=>c.body.includes('dos rondas')));
assert.ok(!(await gh.publicIncidents()).some(i=>i.number===final.number),'El ensayo no debe publicarse como incidencia del servicio');
assert.equal(await gh.trusted('espectre00'),true);
console.log(JSON.stringify({passed:true,issue:final.html_url,duplicate:false,recoveryRounds:2,retained:true,publicServiceIncident:false,regions:second.regions.map(r=>({region:r.region,city:r.city,status:r.status,measurementId:r.measurementId}))},null,2));
